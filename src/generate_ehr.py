"""
Synthetic Electronic Health Record generation for CardioTwin.

Produces a Synthea-style static record per virtual patient: demographics,
ICD-10 coded problem list, laboratory panel, antihypertensive regimen with
dose timing, and a polygenic-risk-score proxy.

The record also carries LATENT traits (dipping phenotype, adherence
propensity, autonomic tone, salt load, OSA severity). Those latents are what
the wearable simulator integrates forward; they are written to a separate
file and are NEVER exposed to the predictive model. They exist so that the
in-silico ground truth is generated by a mechanism rather than by the label.

No real patient data is used anywhere in this project.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from config import SEED, N_PATIENTS, PHENOTYPES, PHENOTYPE_P, DRUGS

ICD10 = {
    "essential_hypertension": "I10",
    "t2dm": "E11.9",
    "dyslipidaemia": "E78.5",
    "ckd3": "N18.3",
    "osa": "G47.33",
    "prior_mi": "I21.9",
    "prior_stroke": "I63.9",
    "obesity": "E66.9",
}

# Indian urban/rural split and state grouping, ICMR-INDIAB sampling frame shape.
REGIONS = ["South", "North", "West", "East", "Northeast", "Central"]
REGION_P = [0.24, 0.22, 0.20, 0.18, 0.06, 0.10]


def _truncnorm(rng, mu, sd, lo, hi, size=None):
    x = rng.normal(mu, sd, size)
    return np.clip(x, lo, hi)


def generate_cohort(n: int = N_PATIENTS, seed: int = SEED) -> tuple[pd.DataFrame, pd.DataFrame]:
    rng = np.random.default_rng(seed)

    pid = [f"PT{i:04d}" for i in range(n)]
    age = _truncnorm(rng, 56, 12, 30, 85, n).round().astype(int)
    sex = rng.choice(["M", "F"], n, p=[0.54, 0.46])
    region = rng.choice(REGIONS, n, p=REGION_P)
    urban = rng.random(n) < 0.62

    # South-Asian phenotype: central adiposity at lower BMI than Western cutoffs.
    bmi = _truncnorm(rng, 26.8, 4.2, 16.0, 44.0, n)
    waist = bmi * 2.9 + np.where(sex == "M", 18.0, 12.0) + rng.normal(0, 5, n)

    # --- comorbidity, partly driven by age/BMI --------------------------------
    p_t2dm = 1 / (1 + np.exp(-(-4.1 + 0.045 * age + 0.085 * (bmi - 25))))
    t2dm = rng.random(n) < p_t2dm
    p_ckd = 1 / (1 + np.exp(-(-5.6 + 0.055 * age + 1.0 * t2dm)))
    ckd3 = rng.random(n) < p_ckd
    p_osa = 1 / (1 + np.exp(-(-4.6 + 0.13 * (bmi - 25) + 0.03 * age + 0.5 * (sex == "M"))))
    osa = rng.random(n) < p_osa
    dyslipidaemia = rng.random(n) < 0.46
    prior_mi = rng.random(n) < (0.05 + 0.08 * t2dm)
    prior_stroke = rng.random(n) < (0.035 + 0.05 * ckd3)
    obesity = bmi >= 30

    # --- labs -----------------------------------------------------------------
    creatinine = _truncnorm(rng, 0.95, 0.22, 0.5, 3.2, n) + 0.45 * ckd3
    # CKD-EPI style monotone surrogate; adequate for a synthetic cohort.
    egfr = np.clip(142 * (creatinine / 0.9) ** -1.2 * (0.9938 ** age) * np.where(sex == "F", 1.012, 1.0), 12, 130)
    hba1c = _truncnorm(rng, 5.6, 0.5, 4.4, 9.0, n) + 1.9 * t2dm
    ldl = _truncnorm(rng, 112, 28, 50, 220, n) + 14 * dyslipidaemia
    sodium = _truncnorm(rng, 139, 2.6, 130, 147, n)
    potassium = _truncnorm(rng, 4.2, 0.42, 3.0, 5.9, n)
    uacr = np.exp(_truncnorm(rng, 2.5, 1.0, 0.0, 7.0, n)) * (1 + 2.2 * ckd3)  # mg/g

    # --- polygenic risk proxy (standardised scalar, as the brief's "genetic marker")
    prs = rng.normal(0, 1, n)

    # --- regimen --------------------------------------------------------------
    n_agents = rng.choice([0, 1, 2, 3], n, p=[0.10, 0.40, 0.34, 0.16])
    drug_names = list(DRUGS)
    regimens, dose_hours = [], []
    for k in n_agents:
        picks = list(rng.choice(drug_names, size=max(k, 0), replace=False)) if k else []
        regimens.append("|".join(picks))
        # Indian practice skews to morning dosing; evening dosing is the lever
        # our twin will later test (chronotherapy).
        dose_hours.append("|".join(str(int(h)) for h in rng.choice([7, 8, 9, 21], size=len(picks),
                                                                   p=[0.42, 0.32, 0.14, 0.12])))

    # --- latent traits (hidden from the model) --------------------------------
    phenotype = rng.choice(PHENOTYPES, n, p=PHENOTYPE_P)
    # OSA and CKD push toward non-dipping / reverse dipping.
    shift = (osa.astype(int) + ckd3.astype(int))
    for i in range(n):
        if shift[i] and phenotype[i] == "dipper" and rng.random() < 0.55:
            phenotype[i] = "non_dipper"
        elif shift[i] == 2 and phenotype[i] == "non_dipper" and rng.random() < 0.4:
            phenotype[i] = "reverse_dipper"

    adherence = np.clip(rng.beta(6.0, 1.9, n), 0.25, 1.0)      # P(takes dose on a given day)
    salt_load = _truncnorm(rng, 9.2, 2.4, 3.5, 18.0, n)         # g/day, Indian diets run high
    autonomic = _truncnorm(rng, 0.0, 1.0, -3, 3, n) - 0.55 * osa - 0.3 * t2dm  # vagal reserve
    sleep_need = _truncnorm(rng, 7.2, 0.7, 5.5, 9.0, n)

    sbp_set = (112
               + 0.33 * age
               + 0.62 * (bmi - 25)
               + 1.70 * salt_load
               + 6.2 * ckd3
               + 2.6 * t2dm
               + 2.4 * prs
               - 1.9 * n_agents
               + rng.normal(0, 6.0, n))
    sbp_set = np.clip(sbp_set, 108, 204)

    ehr = pd.DataFrame({
        "patient_id": pid, "age": age, "sex": sex, "region": region, "urban": urban,
        "bmi": bmi.round(1), "waist_cm": waist.round(1),
        "dx_hypertension": ICD10["essential_hypertension"],
        "dx_t2dm": np.where(t2dm, ICD10["t2dm"], ""),
        "dx_ckd3": np.where(ckd3, ICD10["ckd3"], ""),
        "dx_osa": np.where(osa, ICD10["osa"], ""),
        "dx_dyslipidaemia": np.where(dyslipidaemia, ICD10["dyslipidaemia"], ""),
        "dx_prior_mi": np.where(prior_mi, ICD10["prior_mi"], ""),
        "dx_prior_stroke": np.where(prior_stroke, ICD10["prior_stroke"], ""),
        "dx_obesity": np.where(obesity, ICD10["obesity"], ""),
        "lab_creatinine_mg_dl": creatinine.round(2),
        "lab_egfr": egfr.round(1),
        "lab_hba1c_pct": hba1c.round(1),
        "lab_ldl_mg_dl": ldl.round(0),
        "lab_sodium_mmol_l": sodium.round(1),
        "lab_potassium_mmol_l": potassium.round(2),
        "lab_uacr_mg_g": uacr.round(1),
        "genetic_prs_z": prs.round(3),
        "rx_agents": regimens,
        "rx_dose_hours": dose_hours,
        "rx_n_agents": n_agents,
    })

    latent = pd.DataFrame({
        "patient_id": pid,
        "phenotype": phenotype,
        "adherence": adherence.round(3),
        "salt_load_g": salt_load.round(2),
        "autonomic_z": autonomic.round(3),
        "sleep_need_h": sleep_need.round(2),
        "sbp_setpoint": sbp_set.round(1),
        "osa": osa, "ckd3": ckd3, "t2dm": t2dm,
    })
    return ehr, latent


if __name__ == "__main__":
    import pathlib
    out = pathlib.Path(__file__).resolve().parents[1] / "data"
    out.mkdir(exist_ok=True)
    ehr, latent = generate_cohort()
    ehr.to_csv(out / "ehr.csv", index=False)
    latent.to_csv(out / "latent_truth.csv", index=False)
    print(f"EHR      : {ehr.shape[0]} patients x {ehr.shape[1]} fields -> data/ehr.csv")
    print(f"Latents  : {latent.shape[0]} x {latent.shape[1]} -> data/latent_truth.csv (NOT a model input)")
    print("\nPhenotype mix:")
    print(latent.phenotype.value_counts().to_string())
    print(f"\nComorbidity: T2DM {latent.t2dm.mean():.0%} | CKD3 {latent.ckd3.mean():.0%} | OSA {latent.osa.mean():.0%}")
    print(f"Mean SBP setpoint {latent.sbp_setpoint.mean():.1f} mmHg "
          f"(range {latent.sbp_setpoint.min():.0f}-{latent.sbp_setpoint.max():.0f})")
